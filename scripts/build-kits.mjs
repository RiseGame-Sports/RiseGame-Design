// Builds docs/ui-kits/ds-bundle.js: every export of src/index.js as one browser
// script that sets window.RiseGameDesignSystem_66bdc7. The UI kit pages load React
// from a CDN first, so react and react-dom resolve to window.React and window.ReactDOM.
// Called at the end of scripts/build.mjs. The output is gitignored.
import * as esbuild from 'esbuild';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NAME = 'RiseGameDesignSystem_66bdc7';

const browserReact = {
  name: 'browser-react',
  setup(build) {
    build.onResolve({ filter: /^react(-dom)?$/ }, (args) => ({ path: args.path, namespace: 'browser-react' }));
    build.onLoad({ filter: /.*/, namespace: 'browser-react' }, (args) => ({
      contents: `module.exports = window.${args.path === 'react' ? 'React' : 'ReactDOM'};`,
      loader: 'js',
    }));
  },
};

// src/index.js imports './components/x/Y.js' (the dist file names); the sources are .jsx.
const jsToJsx = {
  name: 'js-to-jsx',
  setup(build) {
    build.onResolve({ filter: /^\.\.?\/.*\.js$/ }, (args) => {
      const file = path.resolve(args.resolveDir, args.path);
      if (existsSync(file)) return undefined;
      const jsx = file.replace(/\.js$/, '.jsx');
      return existsSync(jsx) ? { path: jsx } : undefined;
    });
  },
};

await esbuild.build({
  entryPoints: [path.join(root, 'src/index.js')],
  outfile: path.join(root, 'docs/ui-kits/ds-bundle.js'),
  bundle: true,
  format: 'iife',
  globalName: NAME,
  platform: 'browser',
  target: 'es2018',
  jsx: 'transform',
  loader: { '.jsx': 'jsx', '.js': 'jsx' },
  plugins: [browserReact, jsToJsx],
  // Logo builds its URLs with new URL('../../../assets/...', import.meta.url) from
  // src/components/core. Point import.meta.url at that folder, resolved from the
  // bundle's own URL, so the marks resolve to the repo's assets/.
  define: { 'import.meta.url': '__rgBase' },
  banner: {
    js: "// Generated by scripts/build-kits.mjs. Do not edit.\nvar __rgBase = new URL('../../src/components/core/x.js', document.currentScript.src).href;",
  },
  footer: { js: `window.${NAME} = ${NAME};` },
  logLevel: 'warning',
});
console.log('built docs/ui-kits/ds-bundle.js');
