// Builds dist/ from src/: JSX components to plain ESM, plus CSS, types and tokens.
// Run with `npm run build`.
import { transformAsync } from '@babel/core';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { flatVars, loadTokens, renderTokensCss } from './tokens.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'src');
const dist = path.join(root, 'dist');

async function walk(dir) {
  const out = [];
  for (const e of await fs.readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out;
}

await fs.rm(dist, { recursive: true, force: true });

for (const file of await walk(src)) {
  const rel = path.relative(src, file);
  let target = path.join(dist, rel);
  await fs.mkdir(path.dirname(target), { recursive: true });
  if (file.endsWith('.jsx') || (file.endsWith('.js') && !rel.startsWith('styles'))) {
    const code = (await fs.readFile(file, 'utf8')).replace(/(from\s+['"][^'"]+)\.jsx(['"])/g, '$1.js$2');
    const out = await transformAsync(code, {
      filename: file,
      babelrc: false,
      configFile: false,
      presets: [['@babel/preset-react', { runtime: 'classic' }]],
    });
    target = target.replace(/\.jsx$/, '.js');
    await fs.writeFile(target, out.code + '\n');
  } else {
    await fs.copyFile(file, target);
  }
}

// tokens as JS: the raw tokens.json plus a flat map of CSS custom property -> value
const tokens = loadTokens();
const vars = {};
for (const v of flatVars(tokens)) vars['--' + v.name] = v.ref ? `var(--${v.ref})` : v.value;
await fs.writeFile(path.join(dist, 'styles', 'tokens.css'), renderTokensCss(tokens));
await fs.writeFile(
  path.join(dist, 'tokens.js'),
  `// Generated from tokens/tokens.json by scripts/build.mjs\nexport const tokens = ${JSON.stringify(tokens, null, 1)};\nexport const cssVars = ${JSON.stringify(vars, null, 1)};\nexport default tokens;\n`
);
await fs.writeFile(
  path.join(dist, 'tokens.d.ts'),
  'export declare const tokens: Record<string, any>;\nexport declare const cssVars: Record<string, string>;\nexport default tokens;\n'
);
// fonts: copy the latin woff2 files from @fontsource into dist/fonts and write
// dist/styles/fonts.css, so the styles load no fonts from the network.
const FONTS = [
  { family: 'Barlow Condensed', pkg: 'barlow-condensed', weights: [400, 500, 600, 700] },
  { family: 'Roboto', pkg: 'roboto', weights: [400, 500, 700, 900] },
];
await fs.mkdir(path.join(dist, 'fonts'), { recursive: true });
const faces = [];
for (const { family, pkg, weights } of FONTS) {
  const dir = path.join(root, 'node_modules', '@fontsource', pkg);
  const { version } = JSON.parse(await fs.readFile(path.join(dir, 'package.json'), 'utf8'));
  // The OFL asks for the license to travel with the font files.
  await fs.copyFile(path.join(dir, 'LICENSE'), path.join(dist, 'fonts', `${pkg}-OFL.txt`));
  for (const weight of weights) {
    const file = `${pkg}-latin-${weight}-normal.woff2`;
    await fs.copyFile(path.join(dir, 'files', file), path.join(dist, 'fonts', file));
    // Take the latin unicode-range from Fontsource's own CSS rather than copying it by hand.
    const css = await fs.readFile(path.join(dir, `${weight}.css`), 'utf8');
    const block = css.split(`/* ${pkg}-latin-${weight}-normal */`)[1];
    const range = block && block.match(/unicode-range:\s*([^;]+);/);
    if (!range) throw new Error(`no latin unicode-range for ${pkg} ${weight}`);
    faces.push(
      `/* ${family} ${weight}, latin, from @fontsource/${pkg} ${version} */\n` +
        `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:swap;` +
        `src:url('../fonts/${file}') format('woff2');unicode-range:${range[1].trim()}}`
    );
  }
}
await fs.writeFile(
  path.join(dist, 'styles', 'fonts.css'),
  `/* Generated by scripts/build.mjs from @fontsource. Licensed under the SIL Open Font License 1.1. */\n${faces.join('\n')}\n`
);

console.log('built dist/');

await import('./build-kits.mjs');
